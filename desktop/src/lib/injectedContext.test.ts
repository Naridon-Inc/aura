import { describe, expect, test } from "bun:test";

import {
  compactionHandoff,
  isInjectedOnly,
  visibleUserText,
} from "./injectedContext";

// The risk here is asymmetric. Showing a wrapper is ugly; swallowing a typed
// sentence loses the conversation. So most of these tests are about what
// SURVIVES the filter, not about what it removes.

describe("visibleUserText", () => {
  test("a typed message comes back byte-for-byte", () => {
    const typed = "  fix the retry in cloud_auth.rs — it exits 1 instead of 3\n";
    expect(visibleUserText(typed)).toBe(typed);
    expect(isInjectedOnly(typed)).toBe(false);
  });

  test("a turn that is only the repo's instruction preamble disappears", () => {
    const injected = [
      "# AGENTS.md instructions for /Users/me/Projects/thing",
      "",
      "<INSTRUCTIONS>",
      "# Agent Instructions",
      "",
      "This project uses bd for issue tracking. Run `bd prime`.",
      "</INSTRUCTIONS>",
    ].join("\n");
    expect(visibleUserText(injected)).toBe("");
    expect(isInjectedOnly(injected)).toBe(true);
  });

  test("the human's prompt survives a preamble glued in front of it", () => {
    const both = [
      "# CLAUDE.md instructions for /repo",
      "<INSTRUCTIONS>",
      "Always run the tests.",
      "</INSTRUCTIONS>",
      "",
      "now add the --no-section flag",
    ].join("\n");
    expect(visibleUserText(both)).toBe("now add the --no-section flag");
    expect(isInjectedOnly(both)).toBe(false);
  });

  test("a system-reminder is removed from around the real message", () => {
    const wrapped =
      "<system-reminder>Codebase instructions follow.</system-reminder>\nwhat changed in main?";
    expect(visibleUserText(wrapped)).toBe("what changed in main?");
  });

  test("a paired integration marker and its body go together", () => {
    const beads = [
      "<!-- BEGIN BEADS INTEGRATION v:1 profile:minimal hash:ab12 -->",
      "bd ready   # Find available work",
      "<!-- END BEADS INTEGRATION -->",
      "ship it",
    ].join("\n");
    expect(visibleUserText(beads)).toBe("ship it");
  });

  test("an UNpaired marker is left alone — a lone comment proves nothing", () => {
    const lone = "<!-- BEGIN NOTES -->\nremember to bump the version";
    expect(visibleUserText(lone)).toBe(lone);
    expect(isInjectedOnly(lone)).toBe(false);
  });

  test("a truncated wrapper at the end still hides, and keeps what preceded it", () => {
    const cut = "deploy the console\n<system-reminder>Codebase and user inst";
    expect(visibleUserText(cut)).toBe("deploy the console");
  });

  test("prose that merely mentions an instructions file is not touched", () => {
    const prose = "where are the AGENTS.md instructions for this repo kept?";
    expect(visibleUserText(prose)).toBe(prose);
    expect(isInjectedOnly(prose)).toBe(false);
  });

  test("the local-command caveat banner is dropped, its output is not", () => {
    const replay = [
      "Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.",
      "",
      "git status says the worktree is dirty",
    ].join("\n");
    expect(visibleUserText(replay)).toBe("git status says the worktree is dirty");
  });

  test("asking twice gives the same answer", () => {
    // The `g` flags make this a real hazard, not a hypothetical: a stale
    // lastIndex would make the second call miss and show the preamble.
    const injected = "# AGENTS.md instructions for /repo\nhello";
    expect(visibleUserText(injected)).toBe("hello");
    expect(visibleUserText(injected)).toBe("hello");
    expect(isInjectedOnly(injected)).toBe(false);
    expect(isInjectedOnly(injected)).toBe(false);
  });

  test("empty input stays empty rather than throwing", () => {
    expect(visibleUserText("")).toBe("");
    expect(isInjectedOnly("")).toBe(false);
  });
});

// A compacted run hands its own summary back to itself on the user channel.
// It is the largest thing that has ever been drawn as a message nobody sent —
// a page of "1. Primary Request and Intent" inside a bubble that says the
// person typed it.
describe("a compaction handoff", () => {
  const handoff = [
    "This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation.",
    "",
    "Summary:",
    "1. Primary Request and Intent",
    "The user asked for the retry to use exponential backoff.",
  ].join("\n");

  test("is not drawn as something the person said", () => {
    expect(visibleUserText(handoff)).toBe("");
    expect(isInjectedOnly(handoff)).toBe(true);
  });

  test("is still recognisable, so the transcript can mark the seam", () => {
    expect(compactionHandoff(handoff)?.summary).toBe(
      "1. Primary Request and Intent\nThe user asked for the retry to use exponential backoff.",
    );
  });

  test("keeps the body when the handoff never labels it 'Summary'", () => {
    const older = [
      "This session is being continued from a previous conversation that ran out of context: the conversation is summarized below.",
      "",
      "The user asked for the retry to use exponential backoff.",
    ].join("\n");
    expect(compactionHandoff(older)?.summary).toBe(
      "the conversation is summarized below.\n\nThe user asked for the retry to use exponential backoff.",
    );
  });

  test("a handoff with no body at all is still a handoff", () => {
    const bare =
      "This session is being continued from a previous conversation that ran out of context.";
    expect(compactionHandoff(bare)).toEqual({ summary: "" });
    expect(visibleUserText(bare)).toBe("");
  });

  // The opener is the whole evidence, so it has to be the whole opener. A
  // person writing about compaction is writing a message, and eating it would
  // be the exact failure this module is built to avoid.
  test("someone talking about compaction is left alone", () => {
    const typed =
      "when this session is being continued from a previous conversation that ran out of context, where does the summary come from?";
    expect(compactionHandoff(typed)).toBeNull();
    expect(visibleUserText(typed)).toBe(typed);

    const asQuestion = "why does compaction eat my first message?";
    expect(compactionHandoff(asQuestion)).toBeNull();
    expect(visibleUserText(asQuestion)).toBe(asQuestion);
  });

  test("asking twice gives the same answer", () => {
    expect(compactionHandoff(handoff)).not.toBeNull();
    expect(compactionHandoff(handoff)).not.toBeNull();
    expect(visibleUserText(handoff)).toBe("");
    expect(visibleUserText(handoff)).toBe("");
  });
});
