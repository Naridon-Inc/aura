// What the human actually typed, given what the harness actually sent.
//
// A CLI agent's first "user" turn is routinely not from a user. Claude Code,
// Codex and the rest prepend the repo's instruction file to the session and
// send it down the same channel as typed input: `# AGENTS.md instructions for
// <path>`, an `<INSTRUCTIONS>` wrapper, a `<system-reminder>`, a tool's
// `<!-- BEGIN … -->` block. The engine needs every byte of that. A person
// reading the conversation does not — they see a wall of configuration they
// never wrote, sitting in a bubble styled to say they wrote it, above the
// message they actually sent.
//
// So this strips the scaffolding from the DISPLAY copy only. Nothing here
// touches what is stored, replayed, or sent to the agent; the callers are the
// two transcript renderers and nothing else.
//
// The bias is deliberate and one-directional: recognise wrappers precisely,
// and when nothing is recognised return the text byte-for-byte. The harness
// sometimes appends a real prompt after the preamble, so a filter that is
// vague about where the injected part ends does not merely show noise — it
// eats the sentence the person typed. Every pattern below is a machine-written
// marker with a definite close.

/** A `<system-reminder>` the runtime slipped into the turn. */
const SYSTEM_REMINDER = /<system-reminder>[\s\S]*?<\/system-reminder>/gi;

/** An `<INSTRUCTIONS>` wrapper around a repo's agent rules. */
const INSTRUCTIONS = /<INSTRUCTIONS>[\s\S]*?<\/INSTRUCTIONS>/gi;

/** `# AGENTS.md instructions for /path`, `# CLAUDE.md instructions for …` —
 *  the heading a harness writes above the file it is pasting in. Anchored to
 *  the start of a line and required to name a path, so a human asking "#
 *  AGENTS.md instructions for new hires?" in prose is not matched. */
const FILE_INSTRUCTIONS_HEADING =
  /^[ \t]*#[ \t]+[A-Za-z0-9._-]+[ \t]+instructions for[ \t]+[^\n]+\n?/gim;

/** The banner Claude Code puts above command output replayed as user input. */
const LOCAL_COMMAND_CAVEAT =
  /^[ \t]*Caveat: The messages below were generated by the user while running local commands[^\n]*\n?/gim;

/** A paired `<!-- BEGIN X … --> … <!-- END X … -->` integration block. The
 *  name has to match on both ends: an unpaired marker is left alone, because
 *  a lone comment is not evidence that everything after it is machine-made. */
const PAIRED_MARKER =
  /<!--\s*BEGIN\s+([A-Za-z0-9_][A-Za-z0-9 _-]*?)\s*(?:[^>]*?)-->[\s\S]*?<!--\s*END\s+\1\s*(?:[^>]*?)-->/gi;

/** The handoff a harness writes when a conversation is compacted. The run ran
 *  out of context, the earlier turns were summarised, and the summary is sent
 *  back down the user channel so the model can pick up where it left off.
 *
 *  This one is unlike every other pattern here: there is no closing marker
 *  because there is nothing after it to close. The whole turn is the handoff,
 *  and whatever the person says next arrives as its own turn. So the opener is
 *  required to be at the very start and to be the sentence verbatim — a person
 *  quoting it mid-message is not matched, and a turn that merely mentions
 *  compaction is left alone. */
const COMPACTION_OPENER =
  /^\s*This session is being continued from a previous conversation that ran out of context[.:]/i;

/** Where the summary proper begins, in the handoffs that label it. */
const COMPACTION_SUMMARY_LABEL = /^[ \t]*(?:Summary|Analysis):[ \t]*$/im;

/** What a compacted turn actually is, for a surface that wants to mark the
 *  seam rather than silently skip it. */
export type CompactionHandoff = {
  /** The machine-written summary, without the sentence explaining itself.
   *  Empty when the handoff carried no body. */
  summary: string;
};

/** Read a user turn as a compaction handoff, or `null` when it is not one.
 *
 *  Callers that only draw messages can ignore this — `visibleUserText` already
 *  returns the empty string for a handoff, so it disappears like any other
 *  scaffolding. It exists for the transcript, which would rather show a seam
 *  saying the conversation was summarised here than let the reader wonder why
 *  the agent suddenly knows things nobody asked it. */
export function compactionHandoff(raw: string): CompactionHandoff | null {
  if (!raw || !COMPACTION_OPENER.test(raw)) return null;
  const label = raw.match(COMPACTION_SUMMARY_LABEL);
  const body =
    label?.index != null
      ? raw.slice(label.index + label[0].length)
      : raw.replace(COMPACTION_OPENER, "");
  return { summary: body.trim() };
}

/** An unterminated wrapper at the very end — a turn the runtime truncated. */
const TRAILING_OPEN_REMINDER = /<system-reminder>(?![\s\S]*<\/system-reminder>)[\s\S]*$/i;
const TRAILING_OPEN_INSTRUCTIONS = /<INSTRUCTIONS>(?![\s\S]*<\/INSTRUCTIONS>)[\s\S]*$/i;

/** What a reader should see of a user turn.
 *
 *  Returns the text with every recognised injected wrapper removed, which is
 *  the empty string when the turn was nothing but wrappers — the caller's
 *  signal to draw no bubble at all. Text with no marker in it comes back
 *  unchanged, including its leading and trailing whitespace, so this is safe
 *  to call on every turn. */
export function visibleUserText(raw: string): string {
  if (!raw) return raw;
  // The one turn that is wrapper all the way down: a compaction handoff has
  // no human sentence appended to preserve, so there is nothing to keep.
  if (COMPACTION_OPENER.test(raw)) return "";
  if (!looksInjected(raw)) return raw;

  const withoutWrappers = raw
    .replace(SYSTEM_REMINDER, "")
    .replace(INSTRUCTIONS, "")
    .replace(PAIRED_MARKER, "")
    .replace(FILE_INSTRUCTIONS_HEADING, "")
    .replace(LOCAL_COMMAND_CAVEAT, "")
    .replace(TRAILING_OPEN_REMINDER, "")
    .replace(TRAILING_OPEN_INSTRUCTIONS, "");

  return withoutWrappers.trim();
}

/** Whether a turn is entirely scaffolding, and so should not be drawn. */
export function isInjectedOnly(raw: string): boolean {
  return looksInjected(raw) && visibleUserText(raw).length === 0;
}

/** Cheap guard so the common case — a person typing a sentence — never runs
 *  six regexes, and so text we do not recognise is returned untouched rather
 *  than trimmed. */
function looksInjected(raw: string): boolean {
  return (
    COMPACTION_OPENER.test(raw) ||
    /<system-reminder>/i.test(raw) ||
    /<INSTRUCTIONS>/i.test(raw) ||
    /<!--\s*BEGIN\s+/i.test(raw) ||
    FILE_INSTRUCTIONS_HEADING.test(withFreshIndex(FILE_INSTRUCTIONS_HEADING, raw)) ||
    LOCAL_COMMAND_CAVEAT.test(withFreshIndex(LOCAL_COMMAND_CAVEAT, raw))
  );
}

/** `g`-flagged regexes carry `lastIndex` between `.test()` calls, which makes
 *  the same input answer differently on a second ask. Reset before each use. */
function withFreshIndex(re: RegExp, raw: string): string {
  re.lastIndex = 0;
  return raw;
}
